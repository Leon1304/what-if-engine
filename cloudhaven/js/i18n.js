export function t(key, vars) {
  const e = S[key]; if (!e) return key;
  let v = e[lang === 'en' ? 1 : 0]; if (v === undefined) v = e[0];
  if (typeof v === 'function') return v(vars || {});
  if (typeof v === 'string' && vars) return v.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return v;
}
