// ---------- Sprache wählen ----------
function detect() {
  const saved = loadLang(); if (LANGS.includes(saved)) return saved;
  const nav = typeof navigator !== 'undefined' ? (navigator.languages?.[0] || navigator.language || '') : '';
  return /^de\b/i.test(nav) ? 'de' : 'en';
}
let lang = detect();
const fns = [];
export const getLang = () => lang;
export function setLang(l, save = true) {
  if (!LANGS.includes(l)) return false;
  const changed = l !== lang; lang = l; if (save) saveLang(l);
  applyDoc();
  if (changed) for (const f of fns) try { f(l); } catch (e) { console.warn(e); }
  return changed;
}
export function onLang(fn) { fns.push(fn); return () => { const i = fns.indexOf(fn); if (i >= 0) fns.splice(i, 1); }; }
// <html lang> und Fenstertitel
export function applyDoc() { if (typeof document === 'undefined') return; document.documentElement.lang = lang; document.title = t('game.title'); }

